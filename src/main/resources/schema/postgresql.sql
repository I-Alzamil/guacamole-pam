--
-- Tables of the PAM extension. Every statement is idempotent, and all are run
-- automatically the first time the extension touches the database, unless
-- the database already has the version recorded at the end.
--
-- A later version appends what it changes before that last statement, and
-- records its own number there too (PamDatabase.SCHEMA_VERSION), so this
-- script both creates the tables and upgrades earlier ones.
--

-- Schema versions applied, so later versions can tell what to upgrade.
-- Empty means a fresh install
CREATE TABLE IF NOT EXISTS pam_schema_version (

  version integer NOT NULL,

  PRIMARY KEY (version)

);

-- Platforms: how passwords of a group of systems are managed. Settings,
-- secrets and policy are JSON objects; secrets are never sent to clients
CREATE TABLE IF NOT EXISTS pam_platform (

  platform_id   serial        NOT NULL,
  name          varchar(128)  NOT NULL,
  description   varchar(1024),
  type          varchar(32)   NOT NULL,
  settings      text          NOT NULL DEFAULT '{}',
  secrets       text          NOT NULL DEFAULT '{}',
  policy        text          NOT NULL DEFAULT '{}',
  last_modified timestamptz   NOT NULL DEFAULT CURRENT_TIMESTAMP,

  PRIMARY KEY (platform_id),
  CONSTRAINT pam_platform_name UNIQUE (name)

);

-- Outcome of the latest rotation of each managed connection
CREATE TABLE IF NOT EXISTS pam_rotation_state (

  connection_id    integer       NOT NULL,
  last_attempt     timestamptz,
  last_success     timestamptz,
  last_status      varchar(16),
  last_message     text,
  host_key         varchar(256),

  -- Password generated by an attempt whose outcome could not be confirmed.
  -- Kept so an administrator can recover access to the target
  pending_password varchar(4096),

  PRIMARY KEY (connection_id),
  CONSTRAINT pam_rotation_state_connection
    FOREIGN KEY (connection_id)
    REFERENCES guacamole_connection (connection_id) ON DELETE CASCADE

);

-- Checkouts: who held which Account's password, or access to which
-- connection, why, and until when. Rows are never deleted, so the table
-- doubles as the audit log: deleting a connection keeps its checkouts, with
-- the name it had
CREATE TABLE IF NOT EXISTS pam_checkout (

  checkout_id     serial        NOT NULL,

  -- Null once the connection is deleted
  connection_id   integer,
  connection_name varchar(128)  NOT NULL,

  username        varchar(128)  NOT NULL,

  -- Where the user requested it from, as Guacamole's connection history
  -- records it: the address they logged in from
  remote_host     varchar(256),

  reason          varchar(500)  NOT NULL,
  checked_out     timestamptz   NOT NULL DEFAULT CURRENT_TIMESTAMP,
  expires         timestamptz   NOT NULL,
  released        timestamptz,
  release_reason  varchar(16),
  released_by     varchar(128),

  -- Where who released or revoked the checkout did so from
  released_host   varchar(256),
  reveal_count    integer       NOT NULL DEFAULT 1,

  -- Whether the checkout excluded every other holder
  exclusive       boolean       NOT NULL DEFAULT TRUE,

  -- How many times it was extended, and may be in all
  extensions      integer       NOT NULL DEFAULT 0,
  max_extensions  integer       NOT NULL DEFAULT 0,

  PRIMARY KEY (checkout_id),
  CONSTRAINT pam_checkout_connection
    FOREIGN KEY (connection_id)
    REFERENCES guacamole_connection (connection_id) ON DELETE SET NULL

);

CREATE INDEX IF NOT EXISTS pam_checkout_checked_out
  ON pam_checkout (checked_out);

-- Servers look for checkouts that just ended, to close their sessions
CREATE INDEX IF NOT EXISTS pam_checkout_released
  ON pam_checkout (released);

-- One exclusive holder per connection, and one active checkout per user
CREATE UNIQUE INDEX IF NOT EXISTS pam_checkout_exclusive
  ON pam_checkout (connection_id) WHERE released IS NULL AND exclusive;

CREATE UNIQUE INDEX IF NOT EXISTS pam_checkout_holder
  ON pam_checkout (connection_id, username) WHERE released IS NULL;

-- Requests needing approval. A request is PENDING until enough
-- distinct approvers approve it (APPROVED, which starts its checkout), one
-- denies it (DENIED), its requester cancels it (CANCELLED), or it is left
-- pending for too long (EXPIRED). Like checkouts, kept with the name of
-- their connection once it is deleted
CREATE TABLE IF NOT EXISTS pam_request (

  request_id         serial        NOT NULL,

  -- Null once the connection is deleted
  connection_id      integer,
  connection_name    varchar(128)  NOT NULL,

  username           varchar(128)  NOT NULL,

  -- Where the user requested it from, which its checkout keeps
  remote_host        varchar(256),

  reason             varchar(500)  NOT NULL,
  requested          timestamptz   NOT NULL DEFAULT CURRENT_TIMESTAMP,
  approvals_required integer       NOT NULL,
  status             varchar(16)   NOT NULL DEFAULT 'PENDING',
  decided            timestamptz,
  decided_by         varchar(128),

  -- Where who denied or cancelled the request did so from
  decided_host       varchar(256),
  checkout_id        integer,

  -- Why the approver who decided denied the request
  decision_reason    varchar(500),

  -- When the access asked for starts and ends, for a request made ahead of
  -- time; null for access from the final approval on
  starts             timestamptz,
  ends               timestamptz,

  -- How many times the connection's time limit the access asked for lasts
  periods            integer       NOT NULL DEFAULT 1,

  -- For an extension: the checkout it extends, and by how many minutes
  extends_checkout   integer,
  extension_minutes  integer,

  PRIMARY KEY (request_id),
  CONSTRAINT pam_request_connection
    FOREIGN KEY (connection_id)
    REFERENCES guacamole_connection (connection_id) ON DELETE SET NULL,
  CONSTRAINT pam_request_checkout
    FOREIGN KEY (checkout_id)
    REFERENCES pam_checkout (checkout_id) ON DELETE SET NULL,
  CONSTRAINT pam_request_extends
    FOREIGN KEY (extends_checkout)
    REFERENCES pam_checkout (checkout_id) ON DELETE SET NULL

);

-- At most one pending request per user and connection, besides extensions
CREATE UNIQUE INDEX IF NOT EXISTS pam_request_pending
  ON pam_request (connection_id, username) WHERE status = 'PENDING' AND extends_checkout IS NULL;

-- Approvals given to requests, one per approver
CREATE TABLE IF NOT EXISTS pam_request_approval (

  request_id integer       NOT NULL,
  approver   varchar(128)  NOT NULL,
  approved   timestamptz   NOT NULL DEFAULT CURRENT_TIMESTAMP,

  -- Where the approver approved from
  remote_host varchar(256),

  PRIMARY KEY (request_id, approver),
  CONSTRAINT pam_request_approval_request
    FOREIGN KEY (request_id)
    REFERENCES pam_request (request_id) ON DELETE CASCADE

);

-- Per-user preferences: whether a user sees the badge counting requests
-- awaiting their decision, and (administrators) the badge counting failed
-- rotations; each shown unless turned off
CREATE TABLE IF NOT EXISTS pam_user_preference (

  username       varchar(128)  NOT NULL,
  approval_badge boolean       NOT NULL DEFAULT TRUE,
  rotation_badge boolean       NOT NULL DEFAULT TRUE,

  PRIMARY KEY (username)

);

-- Sessions open on managed connections, on every Guacamole server sharing
-- the database, so all servers can tell whether a connection is in use. Each server refreshes the heartbeat of
-- its own rows, and rows no longer refreshed are removed
CREATE TABLE IF NOT EXISTS pam_session (

  session_id    varchar(36)   NOT NULL,
  connection_id integer       NOT NULL,
  username      varchar(128)  NOT NULL,
  server        varchar(128)  NOT NULL,
  started       timestamptz   NOT NULL DEFAULT CURRENT_TIMESTAMP,
  heartbeat     timestamptz   NOT NULL DEFAULT CURRENT_TIMESTAMP,

  PRIMARY KEY (session_id),
  CONSTRAINT pam_session_connection
    FOREIGN KEY (connection_id)
    REFERENCES guacamole_connection (connection_id) ON DELETE CASCADE

);

-- Sensitive parameters of connections (passwords, private keys,
-- passphrases), kept apart and encrypted while an encryption key is set. The
-- parameter is then a token such as ${PAM_PASSWORD_17}, which the extension
-- replaces when the connection opens
CREATE TABLE IF NOT EXISTS pam_connection_secret (

  connection_id  integer       NOT NULL,
  parameter_name varchar(128)  NOT NULL,
  value          text          NOT NULL,

  PRIMARY KEY (connection_id, parameter_name),
  CONSTRAINT pam_connection_secret_connection
    FOREIGN KEY (connection_id)
    REFERENCES guacamole_connection (connection_id) ON DELETE CASCADE

);

-- Settings of the extension shared by every Guacamole server using the
-- database, set on its settings page. A row records the setting was decided
-- here: its value, or NULL for the default. Without modified_by, it was
-- imported from a server's guacamole.properties
CREATE TABLE IF NOT EXISTS pam_setting (

  name          varchar(64)   NOT NULL,
  value         varchar(1024),
  modified      timestamptz   NOT NULL DEFAULT CURRENT_TIMESTAMP,
  modified_by   varchar(128),

  PRIMARY KEY (name)

);

-- Last, so the default platforms above are only added to a fresh install, and
-- so the extension can tell the schema is complete (PamDatabase.SCHEMA_VERSION)
INSERT INTO pam_schema_version (version) VALUES (1)
ON CONFLICT (version) DO NOTHING;
